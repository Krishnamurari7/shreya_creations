function mapFaqs(rows) {
  return rows.map(([q, qHi, a, aHi]) => ({ q, qHi, a, aHi }));
}

function finalize(course) {
  return { ...course, faqs: mapFaqs(course.faqs) };
}

export const COURSE_LANDINGS = {
  [BASIC.slug]: finalize(BASIC),
  [ADVANCED.slug]: finalize(ADVANCED),
  [COMMANDO.slug]: finalize(COMMANDO),
};

export function getCourseLanding(slug) {
  return COURSE_LANDINGS[slug] || null;
}

/** Fields written to public.courses. Practical syllabus/includes already in the DB are left untouched. */
export function courseRowUpdate(slug) {
  const landing = getCourseLanding(slug);
  if (!landing) return null;
  const about = landing.sections
    .map((section) => {
      const parts = [section.title, ...(section.paragraphs || [])];
      if (section.bullets?.length) parts.push(section.bullets.map((item) => `• ${item}`).join("\n"));
      if (section.items?.length) {
        parts.push(section.items.map((item) => `${item.title}: ${item.body}`).join("\n"));
      }
      return parts.join("\n\n");
    })
    .join("\n\n");
  const aboutHi = landing.sections
    .map((section) => {
      const parts = [section.titleHi || section.title, ...(section.paragraphsHi || section.paragraphs || [])];
      const bullets = section.bulletsHi || section.bullets || [];
      if (bullets.length) parts.push(bullets.map((item) => `• ${item}`).join("\n"));
      const items = section.items || [];
      if (items.length) {
        parts.push(items.map((item) => `${item.titleHi || item.title}: ${item.bodyHi || item.body}`).join("\n"));
      }
      return parts.join("\n\n");
    })
    .join("\n\n");
  const intro = landing.sections[0]?.paragraphs?.[0] || "";
  const introHi = landing.sections[0]?.paragraphsHi?.[0] || intro;
  return {
    title: landing.h1,
    title_hi: landing.h1Hi,
    description: intro,
    description_hi: introHi,
    about,
    about_hi: aboutHi,
    meta_title: landing.metaTitle,
    meta_description: landing.metaDescription,
    image_alt: landing.imageAlt,
    focus_keyword: landing.focusKeyword,
  };
}

export function withLandingSeo(course, landing = getCourseLanding(course?.slug)) {
  if (!course || !landing) return course;
  return {
    ...course,
    meta_title: landing.metaTitle || course.meta_title,
    meta_description: landing.metaDescription || course.meta_description,
    meta_title_hi: landing.metaTitleHi || course.meta_title_hi || course.metaTitleHi,
    meta_description_hi: landing.metaDescriptionHi || course.meta_description_hi || course.metaDescriptionHi,
    image_alt: course.image_alt || landing.imageAlt,
    focus_keyword: course.focus_keyword || landing.focusKeyword,
  };
}
